async function seed() {
  const client = await pool.connect();
  let inserted = 0;
  let skipped = 0;

  try {
    console.log(`Seeding ${CITIES.length} cities into waafi_db...`);

    for (const [city_name, state_region, country] of CITIES) {
      const res = await client.query(
        `INSERT INTO cities (city_name, state_region, country)
         SELECT $1::text, $2::text, $3::text
         WHERE NOT EXISTS (
           SELECT 1 FROM cities
           WHERE LOWER(city_name) = LOWER($1::text) AND LOWER(country) = LOWER($3::text) AND deleted = FALSE
         )`,
        [city_name, state_region, country]
      );
      if (res.rowCount > 0) inserted++;
      else skipped++;
    }

    const countRes = await client.query('SELECT COUNT(*) FROM cities WHERE deleted = FALSE');
    console.log(`\nDone!`);
    console.log(`  Inserted: ${inserted}`);
    console.log(`  Skipped (already exist): ${skipped}`);
    console.log(`  Total active cities in DB: ${countRes.rows[0].count}`);
  } finally {
    client.release();
    await pool.end();
  }
}

seed().catch((err) => { console.error('Seed failed:', err.message); process.exit(1); });
